type NavbarButtonProps = {
  href?: string;
  as?: "a" | "button";
  children: React.ReactNode;
  className?: string;
  variant?: "primary" | "secondary" | "dark" | "gradient";
} & (
  | React.ButtonHTMLAttributes<HTMLButtonElement>
  | React.AnchorHTMLAttributes<HTMLAnchorElement>
);

export const NavbarButton = ({
  href,
  as = "a",
  children,
  className,
  variant = "primary",
  ...props
}: NavbarButtonProps) => {
  const baseStyles =
    "px-4 py-2 rounded-md border border-primary/30 bg-primary text-primary-foreground text-sm font-bold relative cursor-pointer hover:-translate-y-0.5 transition duration-200 inline-block text-center shadow-[0_0_20px_rgba(88,80,236,0.22)]";

  const variantStyles = {
    primary: "bg-primary text-primary-foreground hover:bg-primary/80",
    secondary:
      "bg-primary/10 text-primary border-primary/30 hover:bg-primary/20",
    dark: "bg-[#0f0b16] text-white border border-primary/20 hover:bg-[#17111f]",
    gradient:
      "bg-gradient-to-b from-primary to-primary/80 text-primary-foreground shadow-[0px_2px_0px_0px_rgba(255,255,255,0.15)_inset]",
  };

  const Component = as;

  return (
    <Component
      href={as === "a" ? href || undefined : undefined}
      className={cn(baseStyles, variantStyles[variant], className)}
      {...props}
    >
      {children}
    </Component>
  );
};
